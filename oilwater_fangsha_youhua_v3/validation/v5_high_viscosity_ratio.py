# -*- coding: utf-8 -*-
"""
验证 5：高粘度比下"固定 τ"与"局部混合 τ"的对比（2026-10-25 新增）
------------------------------------------------------------------
为什么要有这个验证：
  旧做法里水格子用 τ_w、油格子用 τ_o，各自固定。粘度比 M 一大，τ_o 就很大
  （τ_o = 0.5 + (τ_w − 0.5)·M_运动）。有壁面时 τ_o ≥ 4.5 在 20 步内发散，
  而你设的 M=20 在 τ_w=0.8 下 τ_o≈7.9、在默认 τ_w=0.7 下 τ_o≈5.5。
  新做法（C++ 参数 MIXTURE_TAU=1）按局部含水比例混合粘度，两套格子在每个格点用同一个 τ。
本脚本在分层 Poiseuille 流（有上下壁面）上把两种做法并排跑一遍，看稳定性和流量误差。

2026-10-25 运行结果（本脚本原样输出整理；全部跑完约 30–40 分钟）：
     τ_w/τ_o（运动粘度比）  固定 τ   混合 τ：L2 误差 / 总流量 / 水层流量 / 油层流量
     0.7/5.45  （24.8）     发散     8.0% / +1.0% / −3.4% / +20.9%     ← 默认 τ_w、M≈20
     0.7/0.995 （2.5）      发散     6.0% / −2.5% / −3.8% /  −0.8%     ← 默认 τ_w、M≈2
     0.8/7.925 （24.7）     发散    10.1% / +3.4% / −3.7% / +35.6%
     0.8/19.0  （61.7）     发散    13.0% / +1.8% / −5.4% / +72.5%
  固定 τ 在 τ_w=0.7 时连粘度比 2.5 都发散（τ_w=0.8、τ_o=2.5 时还能算），所以默认必须 MIXTURE_TAU=1。
  另外：τ_w=0.55 时混合 τ 也发散；τ_w=0.6 时分层流稳定但液滴/接触角算例发散（v2、v3）。
用法：python3 v5_high_viscosity_ratio.py            （跑上表全部）
      python3 v5_high_viscosity_ratio.py 0.6 2.975  （只跑一组）
"""
import sys
from v4_layered_poiseuille import run_case

CASES = [(0.7, 5.45), (0.7, 0.995), (0.8, 7.925), (0.8, 19.0)]   # 默认 τ_w=0.7 下 M≈20、M≈2；τ_w=0.8 下 M≈20、M≈50

if __name__ == "__main__":
    if len(sys.argv) >= 3:
        CASES = [(float(sys.argv[1]), float(sys.argv[2]))]
    for tw, to in CASES:
        print(f"===== τ_w={tw}  τ_o={to} =====", flush=True)
        for mix in (False, True):
            run_case(tw, to, mix=mix)
